-- Esquema de notificaciones. La identidad del id la genera la base de datos tanto en H2 como
-- en PostgreSQL. El estado se guarda como cadena, igual que viaja en la API.
CREATE TABLE notificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario VARCHAR(200) NOT NULL,
    asunto VARCHAR(200) NOT NULL,
    cuerpo VARCHAR(2000) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    motivo_fallo VARCHAR(500)
);
